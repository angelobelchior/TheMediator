using System.Collections.Generic;
using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace TheMediator.Core.SourceGenerator;

[Generator(LanguageNames.CSharp)]
public sealed class TheMediatorSourceGenerator : IIncrementalGenerator
{
    private const string CoreNamespace = "TheMediator.Core";

    private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .WithMiscellaneousOptions(
            SymbolDisplayFormat.FullyQualifiedFormat.MiscellaneousOptions
            | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidateTypes = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax,
                static (ctx, _) => ctx.SemanticModel.GetDeclaredSymbol(ctx.Node) as INamedTypeSymbol)
            .Where(static symbol => symbol is not null);

        var combined = context.CompilationProvider.Combine(candidateTypes.Collect());
        context.RegisterSourceOutput(combined, static (spc, source) => Execute(spc, source.Right));
    }

    private static void Execute(
        SourceProductionContext context,
        ImmutableArray<INamedTypeSymbol?> candidateTypes)
    {
        var registrations = new List<Registration>();

        foreach (var type in candidateTypes)
        {
            if (type is null || type.TypeKind != TypeKind.Class || type.IsAbstract || type.IsGenericType)
                continue;

            if (type.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal))
                continue;

            foreach (var iface in type.AllInterfaces)
            {
                if (IsInterface(iface, "IRequestHandler", 2))
                    registrations.Add(new Registration(type, iface.TypeArguments[0], iface.TypeArguments[1],
                        RegistrationKind.Handler));
                else if (IsInterface(iface, "IRequestHandler", 1))
                    registrations.Add(new Registration(type, iface.TypeArguments[0], null,
                        RegistrationKind.Handler));
                else if (IsInterface(iface, "INotificationHandler", 1))
                    registrations.Add(new Registration(type, iface.TypeArguments[0], null,
                        RegistrationKind.Notifier));
            }
        }

        if (registrations.Count == 0)
            return;

        context.AddSource("TheMediator.Generated.g.cs", BuildSource(registrations));
    }

    private static bool IsInterface(INamedTypeSymbol namedTypeSymbol, string name, int arity)
        => namedTypeSymbol.OriginalDefinition.Name == name
           && namedTypeSymbol.OriginalDefinition.Arity == arity
           && namedTypeSymbol.OriginalDefinition.ContainingNamespace?.ToDisplayString() == CoreNamespace;

    private static string BuildSource(List<Registration> registrations)
    {
        var sb = new StringBuilder();
        foreach (var registration in registrations)
            sb.AppendLine(BuildRegistrationLine(registration));
        sb.AppendLine();

        var code =
            $$"""
              // <auto-generated/>
              #nullable enable
              namespace TheMediator.Generated
              {
                  public static class TheMediatorDI
                  {
                      public static global::TheMediator.Core.DependencyInjection.DependencyInjection.Configuration Register(
                          this global::TheMediator.Core.DependencyInjection.DependencyInjection.Configuration configuration)
                      {
                      {{sb}}
                          return configuration;
                      }
                  }
              }
              """;
        return code;
    }

    private static string BuildRegistrationLine(Registration registration)
    {
        var serviceType = registration.ServiceType.ToDisplayString(TypeFormat);
        return registration.Kind switch
        {
            RegistrationKind.Notifier =>
                  $"            configuration.Notifiers.Add<{serviceType}, {registration.FirstType!.ToDisplayString(TypeFormat)}>();",
            _ => registration.SecondType is not null
                ? $"            configuration.Handlers.Add<{serviceType}, {registration.FirstType!.ToDisplayString(TypeFormat)}, {registration.SecondType.ToDisplayString(TypeFormat)}>();"
                : $"            configuration.Handlers.Add<{serviceType}, {registration.FirstType!.ToDisplayString(TypeFormat)}>();"
        };
    }

    private enum RegistrationKind
    {
        Handler,
        Notifier
    }

    private sealed record Registration(
        INamedTypeSymbol ServiceType,
        ITypeSymbol? FirstType,
        ITypeSymbol? SecondType,
        RegistrationKind Kind);
}
